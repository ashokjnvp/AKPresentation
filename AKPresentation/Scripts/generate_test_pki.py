"""Test-only PKI for AKPresentation tests: credential issuer, IACA/DS, verifier (x509_san_dns), mdoc reader."""
import datetime as dt, os
from cryptography import x509
from cryptography.x509.oid import NameOID, ObjectIdentifier
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

U = dt.timezone.utc
def D(y): return dt.datetime(y, 1, 1, tzinfo=U)
def name(cn, o="AK Test"): return x509.Name([x509.NameAttribute(NameOID.COUNTRY_NAME, "IN"), x509.NameAttribute(NameOID.ORGANIZATION_NAME, o), x509.NameAttribute(NameOID.COMMON_NAME, cn)])
CA = dict(digital_signature=False, content_commitment=False, key_encipherment=False, data_encipherment=False, key_agreement=False, key_cert_sign=True, crl_sign=True, encipher_only=False, decipher_only=False)
LEAF = dict(CA, key_cert_sign=False, crl_sign=False, digital_signature=True)

def cert(subj, key, iname, ikey, serial, ca, eku=None, san=None, pathlen=None):
    b = (x509.CertificateBuilder().subject_name(subj).issuer_name(iname).public_key(key.public_key()).serial_number(serial)
         .not_valid_before(D(2025)).not_valid_after(D(2035))
         .add_extension(x509.BasicConstraints(ca=ca, path_length=pathlen), critical=True)
         .add_extension(x509.KeyUsage(**(CA if ca else LEAF)), critical=True)
         .add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()), critical=False)
         .add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(ikey.public_key()), critical=False))
    if eku: b = b.add_extension(x509.ExtendedKeyUsage(eku), critical=False)
    if san: b = b.add_extension(x509.SubjectAlternativeName([x509.DNSName(s) for s in san]), critical=False)
    return b.sign(ikey, hashes.SHA256())
pem = lambda c: c.public_bytes(serialization.Encoding.PEM).decode().strip()
kpem = lambda k: k.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()).decode().strip()
gen = lambda: ec.generate_private_key(ec.SECP256R1())

out = {}
rk = gen(); root = cert(name("Test Issuer Root"), rk, name("Test Issuer Root"), rk, 1, True)
ik = gen(); leaf = cert(name("issuer.example.com"), ik, root.subject, rk, 2, False, san=["issuer.example.com"])
out.update(issuerRoot=pem(root), issuerSigner=pem(leaf), issuerSignerKey=kpem(ik))
ak = gen(); iaca = cert(name("Test IACA"), ak, name("Test IACA"), ak, 10, True, pathlen=0)
dk = gen(); ds = cert(name("Test Document Signer"), dk, iaca.subject, ak, 11, False, eku=[ObjectIdentifier("1.0.18013.5.1.2")])
out.update(iaca=pem(iaca), documentSigner=pem(ds), documentSignerKey=kpem(dk))
vk = gen(); vroot = cert(name("Test RP Access CA"), vk, name("Test RP Access CA"), vk, 30, True)
vl = gen(); vleaf = cert(name("verifier.example.com", "Example Verifier GmbH"), vl, vroot.subject, vk, 31, False, san=["verifier.example.com"])
out.update(verifierRoot=pem(vroot), verifierCert=pem(vleaf), verifierKey=kpem(vl))
rrk = gen(); rroot = cert(name("Test Reader CA"), rrk, name("Test Reader CA"), rrk, 40, True)
rl = gen(); rleaf = cert(name("Test Reader"), rl, rroot.subject, rrk, 41, False, eku=[ObjectIdentifier("1.0.18013.5.1.6")])
out.update(readerRoot=pem(rroot), readerCert=pem(rleaf), readerKey=kpem(rl))

lines = ["// Generated by Scripts/generate_test_pki.py — test-only keys. Never use in production.", "", "enum TestPKI {"]
for k, v in out.items(): lines.append(f'    static let {k} = """\n{v}\n"""')
lines.append("}")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Tests", "AKPresentationTests", "TestPKI.swift"), "w").write("\n".join(lines) + "\n")
print("ok")
